#!/usr/bin/env python3
"""Generate cli/src/printable_table.rs from the pinned CPython oracle.

The table is the set of code points where CPython `str.isprintable()` is
true (Py_UNICODE_ISPRINTABLE), as contiguous `[start, end)` runs. The
port's `py_repr_str` (cli/src/pytext.rs) escapes non-printable characters
the way CPython `repr()` does, so settings values that reach `str()` /
`%s` as containers (a hand-edited `subtitle_langs` array) render with the
exact same escapes.

Modes:
    --write   regenerate cli/src/printable_table.rs (refuses on oracle drift)
    --check   re-walk the oracle and compare against the committed table
              and the pinned digest; exits nonzero on any mismatch

The pin was recorded 2026-10-15 on CPython 3.14.6 (windows) and 3.14.4
(wsl), both Unicode 16.0.0, with identical bytes. The oracle for the
differential harness is CPython 3.14.x; CI pins python 3.14, so a newer
interpreter with a newer Unicode database fails --check loudly instead of
silently regenerating the table.
"""
import argparse
import hashlib
import re
import sys
import unicodedata
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parent
TABLE_PATH = TOOLS_DIR.parent / "cli" / "src" / "printable_table.rs"
MAX_CP = 0x110000
PRINTABLE_PIN = "56fd2191e3fb8c13110e1f8be9c43755aaf81b071b9ad3240145f3ae5c598625"

ROW_RE = re.compile(r"^\s*\(0x([0-9a-fA-F]+), 0x([0-9a-fA-F]+)\),\s*$")

HEADER = """//! Printable code point table: contiguous runs where CPython
//! `str.isprintable()` is true, generated by tools/gen_printable_table.py
//! from CPython {py}, Unicode {ud}. Do not edit by hand; regenerate with
//! `python3 tools/gen_printable_table.py --write` and keep `--check`
//! green in CI.
//!
//! {count} code points in {n} ranges; ranges sha256 {digest}.

/// `[start, end)` of each run of printable (Py_UNICODE_ISPRINTABLE)
/// code points; the repr of a python string keeps these literal.
pub const PRINTABLE_RANGES: &[(u32, u32)] = &[
"""


def oracle_ranges():
    ranges = []
    start = None
    for cp in range(MAX_CP):
        printable = chr(cp).isprintable()
        if printable and start is None:
            start = cp
        elif not printable and start is not None:
            ranges.append((start, cp))
            start = None
    if start is not None:
        ranges.append((start, MAX_CP))
    return ranges


def blob(ranges):
    return b"".join(b"%08x%08x\n" % (a, b) for a, b in ranges)


def digest(ranges):
    return hashlib.sha256(blob(ranges)).hexdigest()


def render(ranges):
    count = sum(b - a for a, b in ranges)
    header = HEADER.format(
        py=sys.version.split()[0],
        ud=unicodedata.unidata_version,
        count=count,
        n=len(ranges),
        digest=digest(ranges),
    )
    rows = "".join("    (0x%x, 0x%x),\n" % (a, b) for a, b in ranges)
    return header + rows + "];\n"


def parse_committed(path):
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as e:
        print("FAIL cannot read %s: %s" % (path, e))
        return None
    ranges = []
    for line in text.splitlines():
        m = ROW_RE.match(line)
        if m:
            ranges.append((int(m.group(1), 16), int(m.group(2), 16)))
    if not ranges:
        print("FAIL %s carries no table rows" % path)
        return None
    return ranges


def cmd_write():
    ranges = oracle_ranges()
    d = digest(ranges)
    if PRINTABLE_PIN != "PIN_PLACEHOLDER" and d != PRINTABLE_PIN:
        print("FAIL oracle drift: walk digest %s != pinned %s" % (d, PRINTABLE_PIN))
        return 1
    with open(TABLE_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(ranges))
    count = sum(b - a for a, b in ranges)
    print("wrote %s: %d ranges, %d code points, sha256 %s" % (TABLE_PATH, len(ranges), count, d))
    return 0


def cmd_check():
    ranges = oracle_ranges()
    d = digest(ranges)
    ok = True
    if d != PRINTABLE_PIN:
        print("FAIL oracle walk digest %s != pinned %s (unicode %s)"
              % (d, PRINTABLE_PIN, unicodedata.unidata_version))
        ok = False
    committed = parse_committed(TABLE_PATH)
    if committed is None:
        ok = False
    elif committed != ranges:
        print("FAIL committed table differs from the oracle walk "
              "(%d vs %d ranges)" % (len(committed), len(ranges)))
        ok = False
    count = sum(b - a for a, b in ranges)
    print("%s %s: %d ranges, %d code points, sha256 %s"
          % ("PASS" if ok else "FAIL", TABLE_PATH.name, len(ranges), count, d))
    return 0 if ok else 1


def main():
    parser = argparse.ArgumentParser(prog="gen_printable_table.py", description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the rust table")
    group.add_argument("--check", action="store_true", help="verify the committed table")
    args = parser.parse_args()
    return cmd_write() if args.write else cmd_check()


if __name__ == "__main__":
    sys.exit(main())
