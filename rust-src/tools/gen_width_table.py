#!/usr/bin/env python3
"""Generate cli/src/width_table.rs from the pinned CPython reference.

The table is the set of East Asian Width W (Wide) and F (Fullwidth) code
points as contiguous `[start, end)` runs. `dwidth` in cli/src/term.rs
counts these as two terminal columns and everything else as one, exactly
reproducing the python `unicodedata.east_asian_width(ch) in ("W", "F")`
test (audit F10).

Modes:
    --write   regenerate cli/src/width_table.rs (refuses on reference drift)
    --check   re-walk the reference and compare against the committed table
              and the pinned digest; exits nonzero on any mismatch

The pin was recorded 2026-10-14 on CPython 3.14.6 (windows) and 3.14.4
(wsl), both `unicodedata` 16.0.0, with identical bytes. The reference for
the differential harness is CPython 3.14.x; CI pins python 3.14, so a
newer interpreter with a newer Unicode database fails --check loudly
instead of silently regenerating the table.
"""
import argparse
import hashlib
import re
import sys
import unicodedata
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parent
TABLE_PATH = TOOLS_DIR.parent / "cli" / "src" / "width_table.rs"
MAX_CP = 0x110000
EAW_PIN = "73ee3105a481eed7e96b61663338a0f21b600c970b35f728e2b38a55384d06d5"

ROW_RE = re.compile(r"^\s*\(0x([0-9a-fA-F]+), 0x([0-9a-fA-F]+)\),\s*$")

HEADER = """//! East Asian Width table: contiguous runs of Wide and Fullwidth code
//! points, generated by tools/gen_width_table.py from CPython {py}
//! `unicodedata` {ud}. Do not edit by hand; regenerate with
//! `python3 tools/gen_width_table.py --write` and keep `--check` green
//! in CI.
//!
//! {count} code points in {n} ranges; ranges sha256 {digest}.

/// `[start, end)` of each run of East Asian Wide or Fullwidth code
/// points.
pub const WIDE_RANGES: &[(u32, u32)] = &[
"""


def reference_ranges():
    ranges = []
    start = None
    for cp in range(MAX_CP):
        wide = unicodedata.east_asian_width(chr(cp)) in ("W", "F")
        if wide and start is None:
            start = cp
        elif not wide and start is not None:
            ranges.append((start, cp))
            start = None
    if start is not None:
        ranges.append((start, MAX_CP))
    return ranges


def blob(ranges):
    return b"".join(b"%08x%08x\n" % (a, b) for a, b in ranges)


def digest(ranges):
    return hashlib.sha256(blob(ranges)).hexdigest()


def render(ranges):
    count = sum(b - a for a, b in ranges)
    header = HEADER.format(
        py=sys.version.split()[0],
        ud=unicodedata.unidata_version,
        count=count,
        n=len(ranges),
        digest=digest(ranges),
    )
    rows = "".join("    (0x%x, 0x%x),\n" % (a, b) for a, b in ranges)
    return header + rows + "];\n"


def parse_committed(path):
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as e:
        print("FAIL cannot read %s: %s" % (path, e))
        return None
    ranges = []
    for line in text.splitlines():
        m = ROW_RE.match(line)
        if m:
            ranges.append((int(m.group(1), 16), int(m.group(2), 16)))
    if not ranges:
        print("FAIL %s carries no table rows" % path)
        return None
    return ranges


def cmd_write():
    ranges = reference_ranges()
    d = digest(ranges)
    if d != EAW_PIN:
        print("FAIL reference drift: walk digest %s != pinned %s" % (d, EAW_PIN))
        return 1
    with open(TABLE_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(ranges))
    count = sum(b - a for a, b in ranges)
    print("wrote %s: %d ranges, %d code points, sha256 %s" % (TABLE_PATH, len(ranges), count, d))
    return 0


def cmd_check():
    ranges = reference_ranges()
    d = digest(ranges)
    ok = True
    if d != EAW_PIN:
        print("FAIL reference walk digest %s != pinned %s (unicodedata %s)"
              % (d, EAW_PIN, unicodedata.unidata_version))
        ok = False
    committed = parse_committed(TABLE_PATH)
    if committed is None:
        ok = False
    elif committed != ranges:
        print("FAIL committed table differs from the reference walk "
              "(%d vs %d ranges)" % (len(committed), len(ranges)))
        ok = False
    count = sum(b - a for a, b in ranges)
    print("%s %s: %d ranges, %d code points, sha256 %s"
          % ("PASS" if ok else "FAIL", TABLE_PATH.name, len(ranges), count, d))
    return 0 if ok else 1


def main():
    parser = argparse.ArgumentParser(prog="gen_width_table.py", description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the rust table")
    group.add_argument("--check", action="store_true", help="verify the committed table")
    args = parser.parse_args()
    return cmd_write() if args.write else cmd_check()


if __name__ == "__main__":
    sys.exit(main())
